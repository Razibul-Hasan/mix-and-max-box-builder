import { readFile, writeFile } from 'node:fs/promises';

const root = new URL( '../', import.meta.url );
const tokens = JSON.parse(
	await readFile( new URL( 'design/system/tokens.json', root ), 'utf8' )
);
const themed = [ ...tokens.color.tokens, ...tokens.shadow.tokens ];
const declarations = ( items, theme ) =>
	items
		.map(
			( { name, value } ) =>
				`\t--${ name }: ${
					typeof value === 'object' ? value[ theme ] : value
				};`
		)
		.join( '\n' );
const families = Object.entries( tokens.type.families )
	.map( ( [ name, value ] ) => `\t--font-${ name }: ${ value };` )
	.join( '\n' );
const type = tokens.type.groups
	.flatMap( ( group ) =>
		group.styles.flatMap( ( style ) =>
			[ 'fontSize', 'lineHeight', 'fontWeight', 'letterSpacing' ]
				.filter( ( key ) => style[ key ] !== undefined )
				.map(
					( key ) =>
						`\t--${ style.name }-${ key.replace(
							/[A-Z]/g,
							( letter ) => `-${ letter.toLowerCase() }`
						) }: ${ style[ key ] };`
				)
		)
	)
	.join( '\n' );
// Source CSS is in src/styles; webpack preserves the public assets path from build/.
const fonts = tokens.type.fonts
	.map(
		( font ) =>
			`@font-face {\n\tfont-family: "${ font.family }";\n\tsrc: url("../../assets/${ font.file }") format("woff2");\n\tfont-weight: ${ font.weight };\n\tfont-style: ${ font.style };\n\tfont-display: swap;\n}`
	)
	.join( '\n\n' );
const output = `/* Generated by npm run tokens. Commit this file; release builds need no design files. */\n${ fonts }\n\n.mmbb-root {\n${ declarations(
	themed,
	'light'
) }\n${ declarations( [
	...tokens.spacing.tokens,
	...tokens.radius.tokens,
] ) }\n${ families }\n${ type }\n}\n\n.mmbb-root[data-theme="dark"] {\n${ declarations(
	themed,
	'dark'
) }\n}\n`;
// Match the project's CSS lint conventions without changing token values.
const normalized = output
	.replace( 'font-family: "Figtree"', 'font-family: Figtree' )
	.replace( /url\("([^"]+)"\)/g, 'url($1)' )
	.replace(
		/(--font-[^:]+:)([^;]+)/g,
		( _, name, value ) =>
			name +
			value.replace( /\b(Figtree|Menlo|Consolas)\b/g, ( family ) =>
				family.toLowerCase()
			)
	)
	.replace( /#([a-f\d]{8}|[a-f\d]{6})\b/gi, ( hex, digits ) => {
		const pairs = digits.match( /../g );
		return pairs.every( ( pair ) => pair[ 0 ] === pair[ 1 ] )
			? '#' + pairs.map( ( pair ) => pair[ 0 ] ).join( '' )
			: hex;
	} );
await writeFile( new URL( 'src/styles/tokens.css', root ), normalized );
